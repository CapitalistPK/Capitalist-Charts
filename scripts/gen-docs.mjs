import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { CATALOG, COMMON_ATTRIBUTES, EVENTS } from '../packages/elements/dist/catalog.js';

const exampleAttributes = (spec) =>
  [...spec.attributes.slice(0, 2), ...COMMON_ATTRIBUTES.slice(0, 1)]
    .map(({ name, value }) => `${name}="${value}"`)
    .join(' ');

const attributeRows = (attributes) =>
  attributes.map(({ name, value, options, description }) => `| \`${name}\` | \`${options?.join('`, `') || value || '—'}\` | ${description} |`).join('\n');

const sections = CATALOG.map((spec) => `## ${spec.title} — \`<${spec.tag}>\`

${spec.description}

\`\`\`html
<${spec.tag}${exampleAttributes(spec) ? ` ${exampleAttributes(spec)}` : ''}>
  <a href="https://capitalist.pk/psx/ogdc">OGDC share price</a>
</${spec.tag}>
\`\`\`

| Attribute | Values / default | Description |
|---|---|---|
${attributeRows([...COMMON_ATTRIBUTES, ...spec.attributes])}

| Event | Description |
|---|---|
${EVENTS.map(({ name, description }) => `| \`${name}\` | ${description} |`).join('\n')}
`).join('\n');

const markdown = `---
title: Widgets
---

# Widgets

The widget catalog is generated from the built elements package so examples and attributes stay aligned with the public component list.

Hosts can override a reserved widget height with their own CSS \`height\` when their layout needs a different box.

${sections}`;

await writeFile(new URL('../docs/widgets.md', import.meta.url), markdown);

// The README's widget table, between its markers.
const FAMILY = { tickers: 'Tickers', charts: 'Charts', market: 'Market', economy: 'Economy', flows: 'Flows', funds: 'Funds', calendar: 'Calendars', company: 'Company', news: 'News', tools: 'Tools' };
const table = ['| Widget | Family | What it shows |', '|---|---|---|', ...CATALOG.map((w) => `| \`<${w.tag}>\` | ${FAMILY[w.family]} | ${w.description} |`)].join('\n');
const readmeUrl = new URL('../README.md', import.meta.url);
const readme = await readFile(readmeUrl, 'utf8');
await writeFile(readmeUrl, readme.replace(/<!-- widgets:start -->[\s\S]*<!-- widgets:end -->/, `<!-- widgets:start -->\n${CATALOG.length} widgets. Full attributes and examples: [docs/widgets.md](docs/widgets.md).\n\n${table}\n<!-- widgets:end -->`));

// The WordPress plugin's allow-list of widgets and attributes.
const php = `<?php\n// Generated by scripts/gen-docs.mjs from the widget catalog. Do not edit.\nreturn array(\n${CATALOG.map((w) => `\t'${w.tag}' => array(${[...COMMON_ATTRIBUTES, ...w.attributes].map((a) => `'${a.name}'`).join(', ')}),`).join('\n')}\n);\n`;
await writeFile(new URL('../wordpress/capitalist-charts/widgets.php', import.meta.url), php);

// The plugin loads one exact, immutable loader and holds it to an integrity hash, so a later
// release or a tampered CDN file cannot change what runs on a WordPress site.
const { version } = JSON.parse(await readFile(new URL('../packages/elements/package.json', import.meta.url), 'utf8'));
const loader = await readFile(new URL('../packages/elements/cdn/loader.js', import.meta.url));
const integrity = `sha384-${createHash('sha384').update(loader).digest('base64')}`;
const loaderPhp = `<?php\n// Generated by scripts/gen-docs.mjs from the built loader. Do not edit.\nreturn array(\n\t'url' => 'https://capitalist.pk/widgets/v${version}/loader.js',\n\t'integrity' => '${integrity}',\n);\n`;
await writeFile(new URL('../wordpress/capitalist-charts/loader.php', import.meta.url), loaderPhp);
